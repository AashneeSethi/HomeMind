from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
import uuid
from pydantic import BaseModel, Field


def get_utc_now() -> datetime:
    return datetime.now(timezone.utc)


class DecisionType(str, Enum):
    """
    Decisions produced by the DecisionEngine:
    - IGNORE: Event is noisy or irrelevant; discard without notification or state change.
    - UPDATE_CONTEXT_ONLY: Event is meaningful for state tracking but does not warrant interrupting the user.
    - NOTIFY_USER: Event requires alerting or informing the user via an appropriate channel.
    - TRIGGER_ACTION: Event requires an automated home action or multi-device coordination.
    """
    IGNORE = "ignore"
    UPDATE_CONTEXT_ONLY = "update_context_only"
    NOTIFY_USER = "notify_user"
    TRIGGER_ACTION = "trigger_action"


class AgentAction(BaseModel):
    """
    Action generated by HomeMind AgentPlanner in response to events or commands.
    Specifies the decision, the target device (Alexa, Fire TV, etc.), action type, and payload.
    """
    action_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    decision: DecisionType = Field(..., description="The decision classification")
    target_device: Optional[str] = Field(
        default=None,
        description="Target device interface: 'alexa', 'firetv', 'ring', or None"
    )
    action_type: str = Field(
        ...,
        description="Type of action, e.g. 'speak', 'display_overlay', 'log_only', 'mode_change'"
    )
    payload: Dict[str, Any] = Field(
        default_factory=dict,
        description="Device-specific or action-specific parameters"
    )
    reasoning: str = Field(
        default="",
        description="Explanation of why this decision and action were taken"
    )
    created_at: datetime = Field(
        default_factory=get_utc_now,
        description="UTC timestamp when the action was generated"
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "action_id": "act-101",
                "decision": "notify_user",
                "target_device": "alexa",
                "action_type": "speak",
                "payload": {"message": "Someone is at the front door."},
                "reasoning": "Doorbell ring while user is home during daytime."
            }
        }
    }
